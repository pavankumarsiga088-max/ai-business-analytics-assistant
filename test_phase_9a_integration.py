"""
Test Suite for Phase 9A: Streamlit AI Analytics Backend Integration.

Validates the full backend orchestration pipeline:
Uploaded DataFrame -> Schema Extraction -> NL to SQL -> Read-Only Validation -> DuckDB Execution.

CRITICAL REQUIREMENTS:
- Unit tests must NOT make real Gemini API calls or use API quota.
- Uses mock LLM clients.
- Verifies strict read-only security guards and error handling.
"""
import sys
import os
import pandas as pd

# Ensure project root is on Python path
sys.path.insert(0, os.path.abspath(os.path.dirname(__file__)))

from src.data_quality.loader import load_dataset
from src.analytics.duckdb_engine import (
    DuckDBEngine,
    validate_read_only_query,
    DisallowedQueryError,
    QueryExecutionError,
)
from src.analytics.nl_to_sql import (
    generate_sql,
    clean_generated_sql,
    EmptyQuestionError,
    LLMGenerationError,
)


def run_phase_9a_tests():
    print("=" * 78)
    print(" PHASE 9A: STREAMLIT AI ANALYTICS INTEGRATION TEST SUITE")
    print("=" * 78)
    print("Running all offline unit and orchestration tests...\n")

    # Load sample dataset
    sample_path = "sample_data/sample_sales.csv"
    df = load_dataset(sample_path)
    print(f"Loaded sample dataset: {len(df)} rows, {len(df.columns)} columns.\n")

    # -----------------------------------------------------------------
    # TEST 1: Question and actual schema reach generate_sql()
    # -----------------------------------------------------------------
    print("[TEST 1] Verifying that natural-language question and actual schema reach generate_sql()...")
    captured_prompts = []

    def mock_tracking_client(prompt: str) -> str:
        captured_prompts.append(prompt)
        return "SELECT region, SUM(revenue) AS total_revenue FROM sales GROUP BY region;"

    with DuckDBEngine() as engine:
        engine.register_dataframe(df, table_name="sales")
        schema = engine.get_schema("sales")
        
        test_question = "What is the total revenue by region?"
        generated_sql = generate_sql(test_question, schema=schema, llm_client=mock_tracking_client)

    assert len(captured_prompts) == 1, "Prompt was not sent to LLM client"
    prompt_text = captured_prompts[0]
    
    # Verify question is present
    assert test_question in prompt_text, f"Question '{test_question}' not found in generated prompt"
    # Verify table name is sales
    assert "sales" in prompt_text, "Table name 'sales' not found in generated prompt"
    # Verify actual columns from df schema are in prompt
    for col in df.columns:
        assert col in prompt_text, f"Column '{col}' from uploaded DataFrame missing from prompt"

    print("  -> SUCCESS: Question and actual dataset schema reached LLM prompt correctly.\n")

    # -----------------------------------------------------------------
    # TEST 2: Generated SQL is validated before execution
    # -----------------------------------------------------------------
    print("[TEST 2] Verifying that generated SQL is validated with validate_read_only_query()...")
    safe_sql = "SELECT product, AVG(unit_price) FROM sales GROUP BY product;"
    # Must pass without error
    validate_read_only_query(safe_sql)

    unsafe_sql = "DROP TABLE sales;"
    try:
        validate_read_only_query(unsafe_sql)
        raise AssertionError("validate_read_only_query failed to reject DROP TABLE")
    except DisallowedQueryError:
        pass
    print("  -> SUCCESS: validate_read_only_query correctly validates safe and unsafe queries.\n")

    # -----------------------------------------------------------------
    # TEST 3: Safe SELECT query executes successfully against uploaded DataFrame
    # -----------------------------------------------------------------
    print("[TEST 3] Verifying safe analytical SELECT execution through DuckDBEngine...")
    mock_rev_client = lambda p: "SELECT region, SUM(revenue) AS total_revenue FROM sales GROUP BY region ORDER BY total_revenue DESC;"
    
    with DuckDBEngine() as engine:
        engine.register_dataframe(df, table_name="sales")
        schema = engine.get_schema("sales")
        sql = generate_sql("Show revenue by region", schema=schema, llm_client=mock_rev_client)
        validate_read_only_query(sql)
        res_df = engine.execute_query(sql)

    assert isinstance(res_df, pd.DataFrame), "Execution result must be a pandas DataFrame"
    assert len(res_df) == 5, f"Expected 5 regions, got {len(res_df)}"
    assert "region" in res_df.columns and "total_revenue" in res_df.columns
    top_region = res_df.iloc[0]["region"]
    assert top_region == "East", f"Expected top region 'East', got '{top_region}'"
    print(f"  -> SUCCESS: Safe query executed. Returned {len(res_df)} rows. Top region: {top_region}\n")

    # -----------------------------------------------------------------
    # TEST 4: Unsafe SQL generated by LLM is rejected
    # -----------------------------------------------------------------
    print("[TEST 4] Verifying that mutating statements from LLM are rejected...")
    unsafe_payloads = [
        "DROP TABLE sales;",
        "DELETE FROM sales WHERE revenue < 1000;",
        "UPDATE sales SET revenue = 0;",
        "INSERT INTO sales (order_id) VALUES ('HACK');",
        "ALTER TABLE sales DROP COLUMN revenue;",
        "TRUNCATE sales;",
    ]

    with DuckDBEngine() as engine:
        engine.register_dataframe(df, table_name="sales")
        schema = engine.get_schema("sales")

        for bad_sql in unsafe_payloads:
            mock_bad = lambda p, s=bad_sql: s
            gen_bad = generate_sql("malicious intent", schema=schema, llm_client=mock_bad)
            
            # Must be caught either by validate_read_only_query or execute_query
            rejected = False
            try:
                validate_read_only_query(gen_bad)
            except DisallowedQueryError:
                rejected = True

            try:
                engine.execute_query(gen_bad)
                raise AssertionError(f"Security failure: '{bad_sql}' was not blocked by engine!")
            except DisallowedQueryError:
                rejected = True

            assert rejected, f"Mutating SQL '{bad_sql}' bypassed validation!"

    print("  -> SUCCESS: All mutating SQL statements were blocked by read-only security layer.\n")

    # -----------------------------------------------------------------
    # TEST 5: Semicolon multi-statement injection is blocked
    # -----------------------------------------------------------------
    print("[TEST 5] Verifying multi-statement injection protection...")
    injection_sql = "SELECT * FROM sales; DROP TABLE sales;"
    with DuckDBEngine() as engine:
        engine.register_dataframe(df, table_name="sales")
        try:
            validate_read_only_query(injection_sql)
            raise AssertionError("Multi-statement injection was not blocked!")
        except DisallowedQueryError as e:
            assert "Multiple SQL statements" in str(e)

    print("  -> SUCCESS: Semicolon-chained multi-statement injection was blocked.\n")

    # -----------------------------------------------------------------
    # TEST 6: Uploaded DataFrame can be queried and remains unmodified (immutability)
    # -----------------------------------------------------------------
    print("[TEST 6] Verifying DataFrame immutability after querying...")
    df_copy = df.copy(deep=True)
    with DuckDBEngine() as engine:
        engine.register_dataframe(df, table_name="sales")
        _ = engine.execute_query("SELECT COUNT(*) FROM sales;")
        _ = engine.execute_query("SELECT AVG(unit_price) FROM sales;")
    
    assert df.equals(df_copy), "Original DataFrame was mutated during DuckDB execution!"
    print("  -> SUCCESS: DataFrame remains completely unmodified (zero-copy virtual table).\n")

    # -----------------------------------------------------------------
    # TEST 7: Empty question is handled cleanly
    # -----------------------------------------------------------------
    print("[TEST 7] Verifying empty question handling...")
    for empty_val in ["", "   ", "\n\t  ", None]:
        try:
            generate_sql(empty_val, llm_client=lambda p: "SELECT 1;")
            raise AssertionError(f"Expected EmptyQuestionError for '{empty_val}'")
        except EmptyQuestionError:
            pass

    print("  -> SUCCESS: EmptyQuestionError properly raised for whitespace and None questions.\n")

    # -----------------------------------------------------------------
    # TEST 8: Missing or invalid dataset handling
    # -----------------------------------------------------------------
    print("[TEST 8] Verifying handling of missing or invalid dataset...")
    with DuckDBEngine() as engine:
        try:
            engine.register_dataframe(None, table_name="sales")
            raise AssertionError("Expected TypeError for None DataFrame")
        except TypeError:
            pass

        try:
            # Querying an unregistered table
            engine.execute_query("SELECT * FROM non_existent_table;")
            raise AssertionError("Expected QueryExecutionError for missing table")
        except QueryExecutionError:
            pass

    print("  -> SUCCESS: Missing and invalid dataset inputs handled cleanly.\n")

    # -----------------------------------------------------------------
    # TEST 9: Invalid SQL syntax is handled cleanly
    # -----------------------------------------------------------------
    print("[TEST 9] Verifying invalid SQL syntax handling...")
    with DuckDBEngine() as engine:
        engine.register_dataframe(df, table_name="sales")
        invalid_syntax_sql = "SELECT FROM WHERE;"
        try:
            engine.execute_query(invalid_syntax_sql)
            raise AssertionError("Expected QueryExecutionError for syntax error")
        except QueryExecutionError as e:
            assert "Parser Error" in str(e) or "syntax" in str(e).lower()

    print("  -> SUCCESS: Invalid SQL syntax caught as QueryExecutionError.\n")

    # -----------------------------------------------------------------
    # TEST 10: Empty result set handling
    # -----------------------------------------------------------------
    print("[TEST 10] Verifying query returning 0 rows...")
    empty_result_sql = "SELECT * FROM sales WHERE revenue > 999999999;"
    with DuckDBEngine() as engine:
        engine.register_dataframe(df, table_name="sales")
        res_empty = engine.execute_query(empty_result_sql)

    assert isinstance(res_empty, pd.DataFrame), "Result must be a DataFrame"
    assert len(res_empty) == 0, f"Expected 0 rows, got {len(res_empty)}"
    assert len(res_empty.columns) == len(df.columns), "Columns should match table schema"
    print("  -> SUCCESS: Query returning 0 rows handled cleanly without errors.\n")

    print("=" * 78)
    print(" ALL 10 PHASE 9A INTEGRATION TESTS PASSED SUCCESSFULLY!")
    print("=" * 78)


if __name__ == "__main__":
    run_phase_9a_tests()
